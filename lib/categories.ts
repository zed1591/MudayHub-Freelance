/**
 * Get skills associated with a specific category
 */
export function getSkillsForCategory(category: string): string[] {
  if (category in CATEGORY_SKILLS_MAP) {
    return CATEGORY_SKILLS_MAP[category];
  }
  // Try partial match
  const matched = Object.keys(CATEGORY_SKILLS_MAP).find(
    (k) => k.toLowerCase() === category.toLowerCase() || category.toLowerCase().includes(k.toLowerCase())
  );
  if (matched) return CATEGORY_SKILLS_MAP[matched];

  return CATEGORY_SKILLS_MAP["Custom / Other"];
}
